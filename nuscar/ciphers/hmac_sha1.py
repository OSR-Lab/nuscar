import numpy as np
import nuscar
import nuscar.nuscar_rust as _n_rust

BLOCK_SIZE = 64
_INITIAL_HASH = [
    0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476, 0xC3D2E1F0
]
# SHA-1 round constants
_ROUND_K = [0x5A827999] * 20 + [0x6ED9EBA1] * 20 + [0x8F1BBCDC] * 20 + [0xCA62C1D6] * 20


def rotl(x, n):
    return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF


def uint32_to_uint8_array(value):
    """
    Convert a 32-bit integer to a 4-byte numpy uint8 array (big-endian).
    Supports scalar or array input.
    """
    if isinstance(value, (int, np.integer)):
        return np.array([
            (value >> 24) & 0xFF,
            (value >> 16) & 0xFF,
            (value >> 8) & 0xFF,
            value & 0xFF
        ], dtype=np.uint8)
    else:
        value = np.asarray(value, dtype=np.uint32)
        return np.stack([
            (value >> 24) & 0xFF,
            (value >> 16) & 0xFF,
            (value >> 8) & 0xFF,
            value & 0xFF
        ], axis=-1).astype(np.uint8)


def uint8_array_to_uint32(arr):
    """
    Convert a uint8 array to a 32-bit integer (big-endian).
    Supports 1D array of shape (4,) or 2D array of shape (N, 4).
    """
    arr = np.asarray(arr, dtype=np.uint8)
    if arr.ndim == 1:
        return (np.uint32(arr[0]) << 24) | (np.uint32(arr[1]) << 16) | \
               (np.uint32(arr[2]) << 8) | np.uint32(arr[3])
    else:
        return (arr[:, 0].astype(np.uint32) << 24) | \
               (arr[:, 1].astype(np.uint32) << 16) | \
               (arr[:, 2].astype(np.uint32) << 8) | \
               arr[:, 3].astype(np.uint32)


# SHA-1 logic functions
def ch(b, c, d):
    """Ch function: used in rounds 0-19"""
    return (b & c) | (~b & d)


def parity(b, c, d):
    """Parity function: used in rounds 20-39 and 60-79"""
    return b ^ c ^ d


def maj(b, c, d):
    """Maj function: used in rounds 40-59"""
    return (b & c) | (b & d) | (c & d)


def compute_padded_key(key: bytes, pad: int) -> bytes:
    """
    Compute the HMAC padded key.

    Args:
        key: original key, bytes type
        pad: padding byte value, 0x36 (ipad) or 0x5c (opad)
    Returns:
        padded and XORed key, length BLOCK_SIZE (64 bytes)
    """
    # If key length exceeds BLOCK_SIZE, hash it first
    if len(key) > BLOCK_SIZE:
        key = sha1(key)

    # Pad to BLOCK_SIZE
    if len(key) < BLOCK_SIZE:
        key = key + b'\x00' * (BLOCK_SIZE - len(key))

    # XOR with pad
    pad_bytes = bytes([pad] * BLOCK_SIZE)
    padded_key = bytes(k ^ p for k, p in zip(key, pad_bytes))
    return padded_key


def compute_hi_ho(padded_key: bytes) -> list:
    """Compute the initial hash values of HMAC-SHA1 inner/outer hash (after pad processing)"""
    return list(_n_rust.sha1_compute_hi_ho_r(list(padded_key)))


def compute_w(plaintext, w_index):
    """
    Compute the message word W[w_index] of HMAC-SHA1 inner hash.

    Args:
        plaintext: plaintext data, can be bytes or numpy uint8 array
        w_index: message word index (0-79)
    Returns:
        - If plaintext is bytes: returns a single 32-bit integer
        - If plaintext is 1D array: returns uint8 array of shape (4,)
        - If plaintext is 2D array: returns uint8 array of shape (N, 4)
    """
    if isinstance(plaintext, bytes):
        length_in_bits = (BLOCK_SIZE + len(plaintext)) * 8
        data = plaintext + b'\x80'
        while (len(data) * 8) % 512 != 448:
            data += b'\x00'
        data += length_in_bits.to_bytes(8, 'big')
        return sha1_expand_message(data)[w_index]

    # numpy array input
    plaintext = np.asarray(plaintext, dtype=np.uint8)
    if plaintext.ndim == 1:
        plaintext = plaintext[np.newaxis, :]
        result = _n_rust.sha1_compute_w_r(nuscar._global_pool, np.ascontiguousarray(plaintext), w_index)
        return result[0]
    elif plaintext.ndim == 2:
        plaintext = np.ascontiguousarray(plaintext, dtype=np.uint8)
        return _n_rust.sha1_compute_w_r(nuscar._global_pool, plaintext, w_index)


def compute_w0(plaintext):
    return compute_w(plaintext, 0)


def compute_w1(plaintext):
    return compute_w(plaintext, 1)


def compute_delta0(padded_key: bytes) -> np.ndarray:
    """
    Compute the delta0 value of HMAC-SHA1 (e + f(b,c,d) + K[0] + ROTL(a,5)).

    Args:
        padded_key: pad-processed key, bytes type, generated by compute_padded_key(key, 0x36)
    Returns:
        4-byte representation of delta0, numpy uint8 array, shape (4,), big-endian
    """
    a, b, c, d, e = compute_hi_ho(padded_key)
    delta0 = (e + ch(b, c, d) + _ROUND_K[0] + rotl(a, 5)) & 0xFFFFFFFF
    return uint32_to_uint8_array(delta0)


def compute_t0(plaintext: np.ndarray, delta0: np.ndarray):
    """
    Compute the temp value of the first round of the second block of HMAC-SHA1.
    temp = ROTL(a,5) + f(b,c,d) + e + K[0] + W[0]
         = delta0 + W[0]

    Args:
        plaintext: plaintext data, numpy uint8 array, shape (n, m) or (m,)
        delta0: delta0 value, numpy uint8 array, shape (4,) or (n, 4)
    Returns:
        temp0 as 32-bit integer
    """
    w0 = compute_w0(plaintext)
    delta0_val = uint8_array_to_uint32(delta0)
    w0_val = uint8_array_to_uint32(w0)
    return (delta0_val + w0_val) & 0xFFFFFFFF


def compute_t0_hw(plaintext: np.ndarray, delta0: np.ndarray):
    res = uint32_to_uint8_array(compute_t0(plaintext, delta0))
    return nuscar.leakmodel.leakage_model_hw(res, nb_words=1)


def compute_a0_to_e0(padded_key: bytes) -> dict:
    """
    Compute all state values a0 to e0 after compressing the first block (ipad) of HMAC-SHA1.

    Args:
        padded_key: pad-processed key, bytes type, generated by compute_padded_key(key, 0x36)
    Returns:
        dict containing a0 to e0, each value is a numpy uint8 array, shape (4,), big-endian
    """
    a0, b0, c0, d0, e0 = compute_hi_ho(padded_key)
    return {
        'a0': uint32_to_uint8_array(a0),
        'b0': uint32_to_uint8_array(b0),
        'c0': uint32_to_uint8_array(c0),
        'd0': uint32_to_uint8_array(d0),
        'e0': uint32_to_uint8_array(e0)
    }


def attack_delta0_hw(plaintext: np.ndarray, byte_index: int,
                     known_bytes=None, guesses=np.arange(256, dtype=np.uint8)):
    """
    Attack a specific byte of delta0.
    Compute the Hamming weight of the target byte of temp0 = delta0 + W[0]
    using known W[0] and guessed delta0 bytes.

    Args:
        plaintext: array of shape (N, ...)
        byte_index: byte index to attack (0=MSB, 3=LSB)
        known_bytes: list of known lower bytes, ordered from LSB to MSB
        guesses: guess value array, default 0-255
    Returns:
        Hamming weight array of shape (N, 256, 1)
    """
    plaintext = np.asarray(plaintext, dtype=np.uint8)
    if plaintext.ndim == 1:
        plaintext = plaintext[np.newaxis, :]
