def compute_ch_f3(plaintext: np.ndarray, delta0: np.ndarray, r1: np.ndarray,
                   a0_rot30: np.ndarray):
    """
    Compute the Ch function output F3 of round 4.
    F3 = Ch(T1, ROTL(T0, 30), ROTL(a0, 30))

    Args:
        plaintext: plaintext data
        delta0: delta0 value
        r1: R1 value
        a0_rot30: ROTL(a0, 30) value
    Returns:
        F3 as 32-bit integer
    """
    w0 = compute_w0(plaintext)
    w1 = compute_w1(plaintext)

    w0_val = uint8_array_to_uint32(w0)
    w1_val = uint8_array_to_uint32(w1)
    delta0_val = uint8_array_to_uint32(delta0)
    r1_val = uint8_array_to_uint32(r1)
    a0_rot30_val = uint8_array_to_uint32(a0_rot30)

    # Compute T0 and T1
    t0 = (delta0_val + w0_val) & 0xFFFFFFFF
    t1 = (rotl(t0, 5) + r1_val + w1_val) & 0xFFFFFFFF

    # Compute ROTL(T0, 30)
    t0_rot30 = rotl(t0, 30)

    # Compute Ch(T1, ROTL(T0, 30), ROTL(a0, 30))
    # Note: round 4 (i=3) is still in range 0-19, uses Ch function
    f3 = ch(t1, t0_rot30, a0_rot30_val)

    return f3


def compute_ch_f3_hw(plaintext: np.ndarray, delta0: np.ndarray, r1: np.ndarray,
                   a0_rot30: np.ndarray):
    res = compute_ch_f3(plaintext, delta0, r1, a0_rot30)
    return nuscar.leakmodel.leakage_model_hw(uint32_to_uint8_array(res), nb_words=1)


