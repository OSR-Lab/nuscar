#[pyfunction]
pub fn leak_hamming_weight_row_r<'py>(
    _py: Python<'py>,
    p: &ThreadPool,             // thread pool to run in parallel
    data: PyReadonlyArray2<u8>, // data to process
) -> Bound<'py, PyArray1<u8>> {
    let data_r = data.as_array();
    let (nrow, _) = data_r.dim();
    let mut output = Array1::<u8>::zeros(nrow);
    p.on_worker(_py, || {
        Zip::from(&mut output)
            .and(data_r.axis_iter(Axis(0)))
            .par_for_each(|o, row_data| *o = row_data.mapv(|x| HW_LUT[x as usize]).sum())
    });
    return output.to_pyarray_bound(_py);
}
